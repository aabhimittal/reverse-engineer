//! Walking a source tree and building the module graph.
//!
//! Analogy: mapping a city from its road signs. Each `import` is a sign
//! pointing to another district. Following them all gives the road network
//! (module graph). The districts most roads lead *to* are the city centre:
//! the foundational modules you should read first.

use crate::lang::{self, Lang, Loc};
use crate::syntax::{self, FileSyntax};
use rayon::prelude::*;
use serde::Serialize;
use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::path::{Path, PathBuf};

/// Directories that hold third-party or generated code.
pub const SKIP_DIRS: &[&str] = &[
    "node_modules",
    "vendor",
    "third_party",
    "third-party",
    "dist",
    "build",
    "target",
    "out",
    ".venv",
    "venv",
    "env",
    "__pycache__",
    "Pods",
    ".gradle",
    ".idea",
    ".next",
    ".nuxt",
    "coverage",
    "bower_components",
    "site-packages",
    ".tox",
    ".mypy_cache",
    ".pytest_cache",
    "DerivedData",
    ".terraform",
];

/// Maximum file size parsed for syntax (bigger files are counted only).
pub const MAX_PARSE_BYTES: u64 = 1 << 20;

/// One source file.
#[derive(Debug, Clone, Serialize)]
pub struct SourceFile {
    /// Path relative to the root, `/`-separated.
    pub path: String,
    /// Language.
    pub lang: Lang,
    /// Line counts.
    pub loc: Loc,
    /// Size in bytes.
    pub bytes: u64,
    /// Looks generated or minified (skipped for syntax).
    pub generated: bool,
    /// Is a test file.
    pub test: bool,
    /// 1-based line where an inline test region starts (Rust `#[cfg(test)]`), if any.
    pub test_from_line: Option<u32>,
    /// Syntax facts (supported languages only).
    pub syntax: Option<FileSyntax>,
}

impl SourceFile {
    /// Lines of code that are tests (whole file, or the inline test region).
    pub fn test_loc(&self, src_lines_after: impl Fn(u32) -> usize) -> usize {
        if self.test {
            self.loc.code
        } else if let Some(l) = self.test_from_line {
            src_lines_after(l).min(self.loc.code)
        } else {
            0
        }
    }

    /// Is a given line inside test code?
    pub fn is_test_line(&self, line: u32) -> bool {
        self.test || self.test_from_line.is_some_and(|t| line >= t)
    }

    /// Sum of function complexities.
    pub fn complexity(&self) -> u32 {
        self.syntax
            .as_ref()
            .map(|s| s.defs.iter().map(|d| d.complexity).sum())
            .unwrap_or(0)
    }
}

/// A walked and parsed project.
#[derive(Debug, Serialize)]
pub struct Project {
    /// Root directory.
    pub root: PathBuf,
    /// Files (sorted by path).
    pub files: Vec<SourceFile>,
    /// Internal module edges (importer index → imported index).
    pub edges: BTreeSet<(usize, usize)>,
    /// External dependencies → number of importing files.
    pub external: BTreeMap<String, usize>,
    /// Files skipped because of limits.
    pub skipped: usize,
}

fn is_test(path: &str) -> bool {
    let p = path.to_ascii_lowercase();
    let name = p.rsplit('/').next().unwrap_or(&p);
    p.contains("/tests/")
        || p.starts_with("tests/")
        || p.contains("/test/")
        || p.contains("__tests__")
        || p.contains("/spec/")
        || name.starts_with("test_")
        || name.ends_with("_test.go")
        || name.ends_with("_test.py")
        || name.contains(".test.")
        || name.contains(".spec.")
        || name.ends_with("test.java")
        || name.ends_with("tests.rs")
        || p.contains("/fixtures/")
        || p.contains("/testdata/")
        || p.contains("/test_data/")
}

/// Rust convention: `#[cfg(test)] mod tests { … }` sits at the bottom of the file.
fn inline_test_start(lang: Lang, src: &str) -> Option<u32> {
    if lang != Lang::Rust {
        return None;
    }
    src.lines()
        .position(|l| l.trim_start().starts_with("#[cfg(test)]"))
        .map(|i| i as u32 + 1)
}

fn looks_generated(src: &str) -> bool {
    let head = &src[..src.len().min(2048)];
    let lines = src.lines().count().max(1);
    head.contains("@generated")
        || head.contains("DO NOT EDIT")
        || head.contains("Code generated by")
        || (src.len() / lines > 400 && src.len() > 4096)
}

/// Walk and parse a directory (respects `.gitignore`).
pub fn scan(root: &Path, max_files: usize) -> Project {
    let mut paths: Vec<PathBuf> = Vec::new();
    let mut skipped = 0;
    let walker = ignore::WalkBuilder::new(root)
        .hidden(true)
        .git_ignore(true)
        .git_exclude(true)
        .parents(true)
        .filter_entry(|e| {
            let name = e.file_name().to_string_lossy();
            !(e.file_type().is_some_and(|t| t.is_dir()) && SKIP_DIRS.contains(&name.as_ref()))
        })
        .build();
    for entry in walker.flatten() {
        if entry.file_type().is_some_and(|t| t.is_file()) && Lang::from_path(entry.path()).is_some()
        {
            if paths.len() >= max_files {
                skipped += 1;
                continue;
            }
            paths.push(entry.into_path());
        }
    }
    let mut files: Vec<SourceFile> = paths
        .par_iter()
        .filter_map(|p| {
            let lang = Lang::from_path(p)?;
            let meta = std::fs::metadata(p).ok()?;
            let rel = p
                .strip_prefix(root)
                .unwrap_or(p)
                .to_string_lossy()
                .replace('\\', "/");
            let src = if meta.len() <= 8 * MAX_PARSE_BYTES {
                std::fs::read(p).ok()?
            } else {
                Vec::new()
            };
            if src.iter().take(8000).any(|&b| b == 0) {
                return None; // binary file with a source extension
            }
            let src = String::from_utf8_lossy(&src);
            let generated = looks_generated(&src);
            let syntax = if lang.has_syntax() && !generated && meta.len() <= MAX_PARSE_BYTES {
                syntax::extract(lang, &src)
            } else {
                None
            };
            let test_from_line = inline_test_start(lang, &src);
            Some(SourceFile {
                test_from_line,
                loc: lang::count(lang, &src),
                bytes: meta.len(),
                generated,
                test: is_test(&rel),
                path: rel,
                lang,
                syntax,
            })
        })
        .collect();
    files.sort_by(|a, b| a.path.cmp(&b.path));
    let mut p = Project {
        root: root.to_path_buf(),
        files,
        edges: BTreeSet::new(),
        external: BTreeMap::new(),
        skipped,
    };
    p.resolve();
    p
}

fn dir_of(path: &str) -> &str {
    path.rsplit_once('/').map(|(d, _)| d).unwrap_or("")
}

fn join(dir: &str, rel: &str) -> Option<String> {
    let mut parts: Vec<&str> = if dir.is_empty() {
        vec![]
    } else {
        dir.split('/').collect()
    };
    for seg in rel.split('/') {
        match seg {
            "" | "." => {}
            ".." => {
                parts.pop()?;
            }
            s => parts.push(s),
        }
    }
    Some(parts.join("/"))
}

/// Expand one level of Rust use-groups: `crate::{a::B, c}` → `crate::a::B`, `crate::c`.
fn expand_use(u: &str) -> Vec<String> {
    let u: String = u.split_whitespace().collect();
    match (u.find('{'), u.rfind('}')) {
        (Some(o), Some(c)) if o < c => {
            let prefix = &u[..o];
            let mut depth = 0;
            let mut cur = String::new();
            let mut out = Vec::new();
            for ch in u[o + 1..c].chars() {
                match ch {
                    '{' => {
                        depth += 1;
                        cur.push(ch);
                    }
                    '}' => {
                        depth -= 1;
                        cur.push(ch);
                    }
                    ',' if depth == 0 => {
                        out.push(format!("{prefix}{cur}"));
                        cur.clear();
                    }
                    _ => cur.push(ch),
                }
            }
            if !cur.is_empty() {
                out.push(format!("{prefix}{cur}"));
            }
            out
        }
        _ => vec![u],
    }
}

enum Target {
    Internal(Vec<usize>),
    External(String),
    Ignore,
}

impl Project {
    fn index(&self) -> HashMap<&str, usize> {
        self.files
            .iter()
            .enumerate()
            .map(|(i, f)| (f.path.as_str(), i))
            .collect()
    }

    fn resolve(&mut self) {
        let idx = self.index();
        // Python / Java module suffix index: "a/b/c" (no extension) → files.
        let mut by_key: HashMap<String, Vec<usize>> = HashMap::new();
        for (i, f) in self.files.iter().enumerate() {
            if !matches!(f.lang, Lang::Python | Lang::Java) {
                continue;
            }
            let no_ext = f.path.rsplit_once('.').map(|(a, _)| a).unwrap_or(&f.path);
            let key = no_ext.strip_suffix("/__init__").unwrap_or(no_ext);
            let parts: Vec<&str> = key.split('/').collect();
            for k in 0..parts.len() {
                by_key.entry(parts[k..].join("/")).or_default().push(i);
            }
        }
        // Rust crate roots: crate name → lib.rs / main.rs; file → its crate's src dir.
        let mut crates: HashMap<String, usize> = HashMap::new();
        let mut crate_src_dirs: Vec<String> = Vec::new();
        for f in &self.files {
            if f.lang == Lang::Toml && f.path.ends_with("Cargo.toml") {
                let dir = dir_of(&f.path).to_string();
                if let Ok(t) = std::fs::read_to_string(self.root.join(&f.path)) {
                    if let Some(name) = cargo_package_name(&t) {
                        let src = if dir.is_empty() {
                            "src".to_string()
                        } else {
                            format!("{dir}/src")
                        };
                        for root in ["lib.rs", "main.rs"] {
                            if let Some(&i) = idx.get(format!("{src}/{root}").as_str()) {
                                crates.entry(name.replace('-', "_")).or_insert(i);
                            }
                        }
                        crate_src_dirs.push(src);
                    }
                }
            }
        }
        crate_src_dirs.sort_by_key(|d| std::cmp::Reverse(d.len()));
        let go_module = std::fs::read_to_string(self.root.join("go.mod"))
            .ok()
            .and_then(|t| {
                t.lines()
                    .find_map(|l| l.strip_prefix("module ").map(|m| m.trim().to_string()))
            });
        let go_dirs: HashMap<&str, Vec<usize>> = self
            .files
            .iter()
            .enumerate()
            .filter(|(_, f)| f.lang == Lang::Go && !f.test)
            .fold(HashMap::new(), |mut m, (i, f)| {
                m.entry(dir_of(&f.path)).or_default().push(i);
                m
            });

        let mut edges = BTreeSet::new();
        let mut external: BTreeMap<String, usize> = BTreeMap::new();
        for (i, f) in self.files.iter().enumerate() {
            let Some(sx) = &f.syntax else { continue };
            let dir = dir_of(&f.path);
            let mut targets: Vec<Target> = Vec::new();
            match f.lang {
                Lang::Python => {
                    for imp in &sx.imports {
                        targets.push(if imp.starts_with('.') {
                            let dots = imp.chars().take_while(|c| *c == '.').count();
                            let mut base = dir.to_string();
                            for _ in 1..dots {
                                base = dir_of(&base).to_string();
                            }
                            let rest = imp[dots..].replace('.', "/");
                            let key = if rest.is_empty() {
                                base.clone()
                            } else if base.is_empty() {
                                rest
                            } else {
                                format!("{base}/{rest}")
                            };
                            let c: Vec<usize> = [format!("{key}.py"), format!("{key}/__init__.py")]
                                .iter()
                                .filter_map(|p| idx.get(p.as_str()).copied())
                                .collect();
                            if c.is_empty() {
                                Target::Ignore
                            } else {
                                Target::Internal(c)
                            }
                        } else {
                            let key = imp.replace('.', "/");
                            match by_key.get(&key).filter(|v| v.len() == 1) {
                                Some(v) => Target::Internal(v.clone()),
                                None => Target::External(
                                    imp.split('.').next().unwrap_or(imp).to_string(),
                                ),
                            }
                        });
                    }
                }
                Lang::JavaScript | Lang::TypeScript | Lang::Tsx => {
                    for imp in &sx.imports {
                        let spec = imp.as_str();
                        let base = if spec.starts_with('.') {
                            join(dir, spec)
                        } else {
                            spec.strip_prefix("@/")
                                .or_else(|| spec.strip_prefix("~/"))
                                .map(|r| format!("src/{r}"))
                        };
                        targets.push(match base {
                            Some(b) => {
                                let exts = [
                                    "",
                                    ".ts",
                                    ".tsx",
                                    ".js",
                                    ".jsx",
                                    ".mjs",
                                    ".cjs",
                                    "/index.ts",
                                    "/index.tsx",
                                    "/index.js",
                                    "/index.jsx",
                                ];
                                match exts
                                    .iter()
                                    .find_map(|e| idx.get(format!("{b}{e}").as_str()).copied())
                                {
                                    Some(t) => Target::Internal(vec![t]),
                                    None => Target::Ignore,
                                }
                            }
                            None => {
                                let mut parts = spec.split('/');
                                let first = parts.next().unwrap_or(spec);
                                let pkg = if first.starts_with('@') {
                                    format!("{first}/{}", parts.next().unwrap_or(""))
                                } else {
                                    first.to_string()
                                };
                                if pkg.starts_with("node:") {
                                    Target::Ignore
                                } else {
                                    Target::External(pkg)
                                }
                            }
                        });
                    }
                }
                Lang::Go => {
                    for imp in &sx.imports {
                        targets.push(match &go_module {
                            Some(m) if imp.starts_with(&format!("{m}/")) => {
                                let rel = &imp[m.len() + 1..];
                                match go_dirs.get(rel) {
                                    Some(v) => Target::Internal(v.clone()),
                                    None => Target::Ignore,
                                }
                            }
                            _ if !imp.split('/').next().unwrap_or("").contains('.') => {
                                Target::Ignore
                            } // stdlib
                            _ => Target::External(
                                imp.split('/').take(3).collect::<Vec<_>>().join("/"),
                            ),
                        });
                    }
                }
                Lang::Java => {
                    for imp in &sx.imports {
                        let key = imp.trim_end_matches(".*").replace('.', "/");
                        targets.push(match by_key.get(&key) {
                            Some(v) if v.len() <= 3 => Target::Internal(v.clone()),
                            _ if imp.starts_with("java.") || imp.starts_with("javax.") => {
                                Target::Ignore
                            }
                            _ => Target::External(
                                imp.split('.').take(2).collect::<Vec<_>>().join("."),
                            ),
                        });
                    }
                }
                Lang::Rust => {
                    let src_root = crate_src_dirs
                        .iter()
                        .find(|d| f.path.starts_with(&format!("{d}/")))
                        .cloned();
                    let file_stem = f
                        .path
                        .rsplit('/')
                        .next()
                        .unwrap_or("")
                        .trim_end_matches(".rs");
                    let mod_dir = if matches!(file_stem, "mod" | "lib" | "main") {
                        dir.to_string()
                    } else {
                        format!("{dir}/{file_stem}")
                    };
                    for m in &sx.mods {
                        let c: Vec<usize> =
                            [format!("{mod_dir}/{m}.rs"), format!("{mod_dir}/{m}/mod.rs")]
                                .iter()
                                .map(|p| p.trim_start_matches('/').to_string())
                                .filter_map(|p| idx.get(p.as_str()).copied())
                                .collect();
                        if !c.is_empty() {
                            targets.push(Target::Internal(c));
                        }
                    }
                    for u in sx.imports.iter().flat_map(|u| expand_use(u)) {
                        let segs: Vec<&str> = u.split("::").collect();
                        let first = segs.first().copied().unwrap_or("");
                        let rust_target = |base: &str, rest: &[&str]| -> Target {
                            for n in (1..=rest.len()).rev() {
                                let p = format!("{base}/{}", rest[..n].join("/"));
                                for cand in [format!("{p}.rs"), format!("{p}/mod.rs")] {
                                    if let Some(&t) = idx.get(cand.trim_start_matches('/')) {
                                        return Target::Internal(vec![t]);
                                    }
                                }
                            }
                            Target::Ignore
                        };
                        targets.push(match first {
                            "crate" => match &src_root {
                                Some(s) => rust_target(s, &segs[1..]),
                                None => Target::Ignore,
                            },
                            "super" => rust_target(dir_of(&mod_dir), &segs[1..]),
                            "self" => rust_target(&mod_dir, &segs[1..]),
                            "std" | "core" | "alloc" | "" => Target::Ignore,
                            c => match crates.get(c) {
                                Some(&root) => Target::Internal(vec![root]),
                                None => Target::External(c.to_string()),
                            },
                        });
                    }
                }
                _ => {}
            }
            let mut seen_ext = BTreeSet::new();
            for t in targets {
                match t {
                    Target::Internal(v) => {
                        for j in v {
                            if j != i {
                                edges.insert((i, j));
                            }
                        }
                    }
                    Target::External(name) if !name.is_empty() && seen_ext.insert(name.clone()) => {
                        *external.entry(name).or_default() += 1;
                    }
                    _ => {}
                }
            }
        }
        self.edges = edges;
        self.external = external;
    }

    /// In-degree (importers) per file.
    pub fn in_degree(&self) -> Vec<usize> {
        let mut d = vec![0; self.files.len()];
        for &(_, j) in &self.edges {
            d[j] += 1;
        }
        d
    }

    /// PageRank over the import graph: modules that important modules depend on score highest.
    pub fn pagerank(&self, iters: usize) -> Vec<f64> {
        let n = self.files.len();
        if n == 0 {
            return vec![];
        }
        let mut out_deg = vec![0usize; n];
        for &(i, _) in &self.edges {
            out_deg[i] += 1;
        }
        let mut pr = vec![1.0 / n as f64; n];
        let d = 0.85;
        for _ in 0..iters {
            let mut next = vec![(1.0 - d) / n as f64; n];
            let dangling: f64 = (0..n).filter(|&i| out_deg[i] == 0).map(|i| pr[i]).sum();
            for v in next.iter_mut() {
                *v += d * dangling / n as f64;
            }
            for &(i, j) in &self.edges {
                next[j] += d * pr[i] / out_deg[i] as f64;
            }
            pr = next;
        }
        pr
    }

    /// Import cycles (strongly connected components larger than one file).
    pub fn cycles(&self) -> Vec<Vec<usize>> {
        let mut g = petgraph::graphmap::DiGraphMap::<usize, ()>::new();
        for &(i, j) in &self.edges {
            g.add_edge(i, j, ());
        }
        let mut sccs: Vec<Vec<usize>> = petgraph::algo::tarjan_scc(&g)
            .into_iter()
            .filter(|c| c.len() > 1)
            .collect();
        for c in &mut sccs {
            c.sort_unstable();
        }
        sccs.sort_by_key(|c| std::cmp::Reverse(c.len()));
        sccs
    }

    /// Call graph by unique names: (caller "file::fn", callee "file::fn") pairs and fan-in per callee.
    pub fn call_fan_in(&self) -> Vec<(String, String, u32, usize)> {
        let mut defs_by_name: HashMap<&str, Vec<(usize, usize)>> = HashMap::new();
        for (fi, f) in self.files.iter().enumerate() {
            if let Some(sx) = &f.syntax {
                for (di, d) in sx.defs.iter().enumerate() {
                    if d.kind.callable() {
                        defs_by_name
                            .entry(d.name.as_str())
                            .or_default()
                            .push((fi, di));
                    }
                }
            }
        }
        let mut fan_in: HashMap<(usize, usize), BTreeSet<(usize, usize)>> = HashMap::new();
        for (fi, f) in self.files.iter().enumerate() {
            let Some(sx) = &f.syntax else { continue };
            for (di, d) in sx.defs.iter().enumerate() {
                for c in &d.calls {
                    let Some(cands) = defs_by_name.get(c.as_str()) else {
                        continue;
                    };
                    // Prefer a definition in the same file; otherwise require a unique name.
                    let target = cands
                        .iter()
                        .find(|(f2, _)| *f2 == fi)
                        .copied()
                        .or_else(|| (cands.len() == 1).then(|| cands[0]));
                    if let Some(t) = target {
                        if t != (fi, di) {
                            fan_in.entry(t).or_default().insert((fi, di));
                        }
                    }
                }
            }
        }
        let mut out: Vec<(String, String, u32, usize)> = fan_in
            .into_iter()
            .map(|((fi, di), callers)| {
                let f = &self.files[fi];
                let d = &f.syntax.as_ref().expect("syntax").defs[di];
                let name = match &d.container {
                    Some(c) => format!("{c}::{}", d.name),
                    None => d.name.clone(),
                };
                (
                    name,
                    format!("{}:{}", f.path, d.line),
                    d.complexity,
                    callers.len(),
                )
            })
            .collect();
        out.sort_by(|a, b| b.3.cmp(&a.3).then(a.0.cmp(&b.0)));
        out
    }
}

fn cargo_package_name(toml: &str) -> Option<String> {
    let mut in_pkg = false;
    for line in toml.lines() {
        let t = line.trim();
        if t.starts_with('[') {
            in_pkg = t == "[package]";
            continue;
        }
        if in_pkg {
            if let Some(v) = t.strip_prefix("name") {
                let v = v.trim_start().strip_prefix('=')?.trim().trim_matches('"');
                return Some(v.to_string());
            }
        }
    }
    None
}

