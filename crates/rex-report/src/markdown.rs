use rex_core::{Report, SectionBody};
use std::fmt::Write;

fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace(['\n', '\r'], " ")
}

pub(crate) fn render(r: &Report) -> String {
    let mut o = String::new();
    let _ = writeln!(o, "# {}\n", r.title);
    let a = &r.artifact;
    let _ = writeln!(o, "| Property | Value |\n|---|---|");
    let _ = writeln!(o, "| Name | `{}` |", cell(&a.name));
    if let Some(k) = a.kind {
        let _ = writeln!(o, "| Kind | {} |", k.label());
    }
    let _ = writeln!(o, "| Size | {} |", crate::human_size(a.size));
    if let Some(h) = &a.sha256 {
        let _ = writeln!(o, "| SHA-256 | `{h}` |");
    }
    let _ = writeln!(o, "| Generated by | {} {} |", r.tool.name, r.tool.version);

    if !r.findings.is_empty() {
        let _ = writeln!(o, "\n## Findings\n");
        let _ = writeln!(
            o,
            "| Severity | Finding | Category | Rule |\n|---|---|---|---|"
        );
        for f in &r.findings {
            let _ = writeln!(
                o,
                "| **{}** | {} | {} | `{}` |",
                f.severity,
                cell(&f.title),
                cell(&f.category),
                f.id
            );
        }
        let detailed: Vec<_> = r
            .findings
            .iter()
            .filter(|f| !f.description.is_empty() || !f.evidence.is_empty())
            .collect();
        if !detailed.is_empty() {
            let _ = writeln!(o, "\n<details><summary>Finding details</summary>\n");
            for f in detailed {
                let _ = writeln!(o, "#### {} `{}`\n", f.title, f.id);
                if !f.description.is_empty() {
                    let _ = writeln!(o, "{}\n", f.description);
                }
                for e in f.evidence.iter().take(20) {
                    let _ = writeln!(o, "- `{}`", e.replace('`', "'"));
                }
                if !f.attack.is_empty() {
                    let _ = writeln!(o, "\nATT&CK: {}", f.attack.join(", "));
                }
                o.push('\n');
            }
            let _ = writeln!(o, "</details>");
        }
    }

    for s in &r.sections {
        let _ = writeln!(o, "\n## {}\n", s.title);
        match &s.body {
            SectionBody::KeyValue { pairs } => {
                let _ = writeln!(o, "| Key | Value |\n|---|---|");
                for (k, v) in pairs {
                    let _ = writeln!(o, "| {} | {} |", cell(k), cell(v));
                }
            }
            SectionBody::Table {
                columns,
                rows,
                truncated,
            } => {
                if rows.is_empty() {
                    let _ = writeln!(o, "_None._");
                    continue;
                }
                let _ = writeln!(
                    o,
                    "| {} |\n|{}|",
                    columns
                        .iter()
                        .map(|c| cell(c))
                        .collect::<Vec<_>>()
                        .join(" | "),
                    columns.iter().map(|_| "---").collect::<Vec<_>>().join("|")
                );
                for row in rows {
                    let _ = writeln!(
                        o,
                        "| {} |",
                        row.iter().map(|c| cell(c)).collect::<Vec<_>>().join(" | ")
                    );
                }
                if *truncated > 0 {
                    let _ = writeln!(o, "\n_…and {truncated} more rows._");
                }
            }
            SectionBody::Text { text } => {
                let _ = writeln!(o, "{text}");
            }
            SectionBody::Code { lang, text } => {
                let _ = writeln!(o, "```{lang}\n{}\n```", text.trim_end());
            }
            SectionBody::Diagram { kind, text } => {
                let _ = writeln!(o, "```{kind}\n{}\n```", text.trim_end());
            }
        }
    }
    if !r.errors.is_empty() {
        let _ = writeln!(o, "\n## Analyzer warnings\n");
        for e in &r.errors {
            let _ = writeln!(o, "- {e}");
        }
    }
    o
}
